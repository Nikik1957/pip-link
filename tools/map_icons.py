def rows(name):
    r = [l for l in ART[name].strip("\n").split("\n")]
    assert len(r) == 16, (name, len(r))
    for l in r:
        assert len(l) == 16, (name, l)
    return r


def icons_bin():
    out = bytearray()
    for t in TYPES:
        for line in rows(t):
            v = 0
            for ch in line:
                v = (v << 1) | (1 if ch == "#" else 0)
            out += bytes([v >> 8, v & 0xFF])
    return bytes(out)


def type_index(name):
    return TYPES.index(name)


